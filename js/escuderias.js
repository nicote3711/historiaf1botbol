function iniciarEscuderias()
{
    const botones = document.querySelectorAll(".boton-escuderia");

    for (let i = 0; i < botones.length; i++)
    {
        botones[i].addEventListener("click",seleccionarEscuderiaHistorica);
    }

    mostrarEscuderia(0);
}


function seleccionarEscuderiaHistorica(evento)
{
    const indice = Number(evento.currentTarget.dataset.indice);

    mostrarEscuderia(indice);

    actualizarBotonEscuderia(indice);
}


function mostrarEscuderia(indice)
{
    const escuderia = escuderiasHistoricas[indice];

    document.getElementById("nombre-escuderia").textContent = escuderia.nombre;

    document.getElementById("periodo-escuderia").textContent = escuderia.periodo;

    document.getElementById("estado-escuderia").textContent = escuderia.estado;

    document.getElementById("debut-escuderia").textContent = escuderia.debut;

    document.getElementById("constructores-escuderia").textContent = escuderia.constructores;

    document.getElementById("pilotos-titulos-escuderia").textContent = escuderia.pilotosTitulos;

    document.getElementById("pilotos-escuderia").textContent = escuderia.pilotos;

    document.getElementById("historia-escuderia").textContent = escuderia.historia;

    document.getElementById("legado-escuderia").textContent = escuderia.legado;

    document.getElementById("logo-escuderia").src = escuderia.imagen;

    document.getElementById("logo-escuderia").alt = escuderia.alt;
}


function actualizarBotonEscuderia(indice)
{
    const botones = document.querySelectorAll(".boton-escuderia");

    for (let i = 0; i < botones.length; i++)
    {
        botones[i].classList.remove("activo-escuderia");
    }

    botones[indice].classList.add("activo-escuderia");
}


iniciarEscuderias();